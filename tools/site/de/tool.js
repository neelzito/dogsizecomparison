/*
 * German comparison tool:
 *   - js/i18n-de.js: German breed names, page URLs and group/size/origin names for
 *     js/app.js, js/calc.js and js/finder.js (they check window.I18N),
 *   - de/index.html: index.html with every visible English text replaced.
 * Every English string below must still be found in index.html; the build stops
 * otherwise, so a changed English text can't silently stay untranslated.
 */
const L = require("../lib");
const D = require("./lang");
const { fs, path, ROOT, esc, avg, BREEDS, BY_ID, N, GROUPS, SIZES, CABIN, CABIN_MAX_DOG, cabin } = L;
const { n, name, H, W, cm, kg, num } = D;

module.exports = function buildTool(indexHtml, pairs) {
  // ---------- js/i18n-de.js ----------
  const origins = {};
  for (const b of BREEDS) origins[b.origin] = D.originName(b.origin);
  const data = {
    lang: "de",
    names: Object.fromEntries(BREEDS.map((b) => [b.id, n(b)])),
    urls: Object.fromEntries(BREEDS.map((b) => [b.id, D.breedUrl(b)])),
    /** [article, name after the article] for "Der Deutsche Schäferhund ist …" */
    der: Object.fromEntries(BREEDS.map((b) => { const s = name.der(b); const i = s.indexOf(" "); return [b.id, [s.slice(0, i), s.slice(i + 1)]]; })),
    sizes: Object.fromEntries(SIZES.map((s) => [s, D.SIZE_DE[s].short])),
    groups: Object.fromEntries(GROUPS.map((g) => [g, D.groupName(g)])),
    origins,
  };
  fs.writeFileSync(path.join(ROOT, "js/i18n-de.js"), `// Generated by tools/site/de/tool.js — German names and URLs for the scripts on /de/ pages.\nwindow.I18N = ${JSON.stringify(data)};\n`);

  // ---------- de/index.html ----------
  let html = indexHtml;
  const put = (marker, content) => {
    const re = new RegExp(`(<!-- ${marker} -->)[\\s\\S]*?(<!-- /${marker} -->)`);
    if (!re.test(html)) throw new Error(`de/index.html: marker ${marker} missing in index.html`);
    html = html.replace(re, (_, a, b) => `${a}\n${content}\n${b}`);
  };
  const rep = (en, de, all = false) => {
    if (!html.includes(en)) throw new Error(`de/index.html: English text not found in index.html (update tools/site/de/tool.js):\n  ${en}`);
    html = all ? html.split(en).join(de) : html.replace(en, de);
  };
  const title = `Hundegrößen-Vergleich: ${N} Hunderassen maßstabsgetreu nebeneinander`;
  const desc = `Vergleiche die Größe von ${N} Hunderassen maßstabsgetreu nebeneinander. Schulterhöhe und Gewicht von Rüden und Hündinnen, mit allen Bereichen in cm und kg.`;

  html = html.replace(/<html lang="en">/, '<html lang="de">')
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)}</title>`)
    .replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${esc(desc)}" />`)
    .replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${L.SITE}/de/" />`)
    .replace(/<meta property="og:site_name" content="[^"]*" \/>/, `<meta property="og:site_name" content="${D.SITE_NAME_DE}" />\n  <meta property="og:locale" content="de_DE" />`)
    .replace(/<meta property="og:url" content="[^"]*" \/>/, `<meta property="og:url" content="${L.SITE}/de/" />`)
    .replace(/<meta property="og:title" content="[^"]*" \/>/, `<meta property="og:title" content="${esc(title)}" />`)
    .replace(/<meta property="og:description" content="[^"]*" \/>/, `<meta property="og:description" content="${esc(desc)}" />`)
    .replace(/<meta property="og:image" content="[^"]*" \/>/, `<meta property="og:image" content="${L.SITE}/img/og-image-de.png" />`)
    .replace(/<meta property="og:image:alt" content="[^"]*" \/>/, `<meta property="og:image:alt" content="Illustrierte Hunderassen vom Chihuahua bis zum Irischen Wolfshund, maßstabsgetreu nebeneinander" />`)
    // root-relative paths, since the page lives at /de/
    .replace(/(href|src)="(css|js|img)\//g, '$1="/$2/').replace(/href="favicon\.ico"/, 'href="/favicon.ico"');

  put("site:topbar", D.topbar("/de/#"));
  put("site:footer", D.siteFooter());
  put("site:hreflang", L.HREFLANG);
  put("seo:ld", ldBlock());
  put("seo:library", libraryBlock());
  put("seo:faq", faqBlock());
  rep('<script src="/js/breeds.js" defer></script>', '<script src="/js/i18n-de.js" defer></script>\n  <script src="/js/breeds.js" defer></script>');

  // static text, in page order
  const T = [
    ["<h1>Dog Size Comparison</h1>", "<h1>Hundegrößen-Vergleich</h1>"],
    ["Put up to 10 breeds side by side, drawn to scale. Pick male, female or both, and see the full height and weight ranges.", "Stell bis zu 10 Rassen maßstabsgetreu nebeneinander. Wähle Rüde, Hündin oder beide und sieh dir die vollen Größen- und Gewichtsbereiche an."],
    ['aria-label="Selected breeds and settings"', 'aria-label="Ausgewählte Rassen und Einstellungen"'],
    ['placeholder="Add a breed… (e.g. Labrador, Corgi)"', 'placeholder="Rasse hinzufügen … (z. B. Labrador, Dackel)"'],
    ['aria-label="Breeds being compared"', 'aria-label="Verglichene Rassen"'],
    [">+ Add your own dog</button>", ">+ Eigenen Hund hinzufügen</button>"],
    ["<label>Name<input", "<label>Name<input"],
    ['placeholder="My dog"', 'placeholder="Mein Hund"'],
    ["<label>Height at shoulder<span>", "<label>Schulterhöhe<span>"],
    ["<label>Weight<span>", "<label>Gewicht<span>"],
    ["<label>Looks most like<select", "<label>Sieht am ehesten aus wie<select"],
    [">Add to comparison</button>", ">Zum Vergleich hinzufügen</button>"],
    [">Cancel</button>", ">Abbrechen</button>"],
    ['<span class="control-label">Sex (all)</span>', '<span class="control-label">Geschlecht (alle)</span>'],
    ['aria-label="Sex for all breeds"', 'aria-label="Geschlecht für alle Rassen"'],
    ['<button data-v="m">♂ Male</button><button data-v="f">♀ Female</button><button data-v="both">Both</button>', '<button data-v="m">♂ Rüde</button><button data-v="f">♀ Hündin</button><button data-v="both">Beide</button>'],
    ['<span class="control-label">Units</span>', '<span class="control-label">Einheiten</span>'],
    ['aria-label="Units"', 'aria-label="Einheiten"'],
    ['<span class="control-label">Draw at</span>', '<span class="control-label">Zeichnen bei</span>'],
    ['aria-label="Which size to draw"', 'aria-label="Welche Größe gezeichnet wird"'],
    ['<button data-v="min">Min</button><button data-v="avg">Average</button><button data-v="max">Max</button>', '<button data-v="min">Min.</button><button data-v="avg">Durchschnitt</button><button data-v="max">Max.</button>'],
    ['<span class="control-label">Human reference</span>', '<span class="control-label">Mensch zum Vergleich</span>'],
    ['aria-label="Show a person for scale"', 'aria-label="Einen Menschen als Maßstab zeigen"'],
    ['aria-label="Human height"', 'aria-label="Größe des Menschen"'],
    ['<span class="control-label">Range markers</span>', '<span class="control-label">Bereichsmarken</span>'],
    ['aria-label="Show size range markers"', 'aria-label="Größenbereiche anzeigen"'],
    ['aria-label="Size visualisation"', 'aria-label="Größendarstellung"'],
    [">⤓ Download image</button>", ">⤓ Bild herunterladen</button>"],
    [">Share image</button>", ">Bild teilen</button>"],
    ["Each dog is scaled by its height at the withers (top of the shoulder). Heads and ears rise above that line, as on a real dog. Illustrations show a typical coat and colour for the breed; the line under each dog matches its number.", "Jeder Hund ist nach seiner Widerristhöhe (höchster Punkt der Schulter) skaliert. Kopf und Ohren ragen darüber hinaus, wie bei einem echten Hund. Die Illustrationen zeigen ein typisches Fell und eine typische Farbe der Rasse; die Linie unter jedem Hund passt zu seiner Nummer."],
    ["<h2>Height at withers</h2>", "<h2>Schulterhöhe</h2>"],
    ["<h2>Weight</h2>", "<h2>Gewicht</h2>"],
    ["<h2>All the numbers</h2>", "<h2>Alle Zahlen</h2>"],
    [">Copy link to this comparison</button>", ">Link zu diesem Vergleich kopieren</button>"],
    ['aria-label="Breed library"', 'aria-label="Rassenliste"'],
    ["<h2>Breed library ", "<h2>Rassenliste "],
    ['<a class="suggest-link" href="/suggest-a-breed/">Missing a breed?</a>', '<a class="suggest-link" href="/de/rasse-vorschlagen/">Fehlt eine Rasse?</a>'],
    ['placeholder="Filter breeds…"', 'placeholder="Rassen filtern …"'],
    ['aria-label="Group"', 'aria-label="Gruppe"'],
    ['aria-label="Sort"', 'aria-label="Sortierung"'],
    ['<option value="name">Sort: A–Z</option>', '<option value="name">Sortierung: A–Z</option>'],
    ['<option value="h-desc">Tallest first</option>', '<option value="h-desc">Größte zuerst</option>'],
    ['<option value="h-asc">Smallest first</option>', '<option value="h-asc">Kleinste zuerst</option>'],
    ['<option value="w-desc">Heaviest first</option>', '<option value="w-desc">Schwerste zuerst</option>'],
    ['<option value="w-asc">Lightest first</option>', '<option value="w-asc">Leichteste zuerst</option>'],
    ['aria-label="Airplane cabin"', 'aria-label="Flugzeugkabine"'],
    ['<option value="">Airplane: any</option>', '<option value="">Flugzeug: alle</option>'],
    ['<option value="yes">✈ Airplane friendly</option>', '<option value="yes">✈ Flugzeugtauglich</option>'],
    ['<option value="some">✈ Airplane friendly (incl. some)</option>', '<option value="some">✈ Flugzeugtauglich (inkl. teils)</option>'],
  ];
  for (const [en, de] of T) rep(en, de);
  // the small print under the tool
  html = html.replace(/(<footer class="foot">\s*<p>)[\s\S]*?(<\/p>\s*<\/footer>)/, (_, a, b) => `${a}Die Zahlen stammen von den Rasseseiten des American Kennel Club, ergänzt um Standards der FCI, des UKC und der Rasseclubs für Rassen, die der AKC nicht führt. Nennt ein Standard nur einen Wert (z. B. „27 Zoll“), zeigt der Bereich genau diesen Wert; nennt er keinen (z. B. „Hündinnen etwas kleiner“), steht ein typischer Wert da, in der Tabelle mit ⚠ markiert. Designer- und Mischlingsrassen haben keinen Standard, ihre Bereiche sind typische Werte. Einzelne Hunde können außerhalb aller angegebenen Bereiche liegen. Zuletzt geprüft im November 2026.${b}`);

  const file = path.join(ROOT, "de", "index.html");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, L.finalizeHtml(html, "/de/", pairs));

  // ---------- generated blocks ----------
  function libraryBlock() {
    return D.sortDe(BREEDS).map((b) => `<button class="lib-item" data-id="${b.id}" aria-pressed="false"><img class="lib-thumb" src="/img/dogs/thumb/${b.id}.webp" alt="${esc(n(b))}" loading="lazy" decoding="async" width="64" height="44"><span class="meta"><span class="nm" style="display:block">${esc(n(b))}</span>`
      + `<span class="st" style="display:block">♂ ${H(b.m.h)} · ${W(b.m.w)}</span><span class="st" style="display:block">♀ ${H(b.f.h)} · ${W(b.f.w)}</span></span><span class="add">+</span></button>`).join("\n");
  }
  function faqs() {
    const by = (k, dir) => [...BREEDS].sort((a, b) => dir * (a[k] - b[k]));
    const tall = by("hAvg", -1), heavy = by("wAvg", -1), short = by("hAvg", 1), light = by("wAvg", 1);
    const nCabin = BREEDS.filter((b) => cabin(b) === "yes").length, nSome = BREEDS.filter((b) => cabin(b) === "some").length;
    const lst = (bs) => D.listDe(bs.map((b) => name.der(b)));
    return [
      ["Wie misst man die Größe eines Hundes?", "Gemessen wird am Widerrist, dem höchsten Punkt der Schulterblätter, vom Boden aus, während der Hund gerade steht. Kopf und Ohren zählen nicht mit, deshalb ist ein Hund insgesamt größer als die Zahl im Rassestandard. Diese Seite skaliert jeden Hund nach seiner Widerristhöhe."],
      ["Sind Rüden und Hündinnen unterschiedlich groß?", "Bei den meisten Rassen sind Rüden größer und schwerer als Hündinnen, oft um 2–5 cm und 10–25 % beim Gewicht. Manche Standards nennen für beide Geschlechter denselben Bereich; dann zeigt die Seite für Rüde und Hündin dieselben Werte. Mit den Schaltern Rüde, Hündin oder Beide kannst du sie vergleichen."],
      ["Welche ist die größte Hunderasse?", `Im Durchschnitt ist ${name.der(tall[0])} hier die größte Rasse, mit ${H(tall[0].m.h)} bei Rüden. Danach folgen ${lst(tall.slice(1, 4))}. Am schwersten sind ${lst(heavy.slice(0, 3))}, mit Rüden bis zu ${kg(heavy[0].m.w[1])} kg.`],
      ["Welche ist die kleinste Hunderasse?", `${D.cap(name.der(light[0]))} ist die leichteste Rasse, mit ${W(light[0].m.w)}. ${D.cap(name.der(short[0]))} ist an der Schulter am kleinsten, mit ${H(short[0].m.h)}. Weitere sehr kleine Rassen sind ${lst(light.slice(1, 4))}.`],
      ["Welche Hunderassen dürfen in die Flugzeugkabine?", `Viele europäische Airlines erlauben Hunde in der Kabine nur, wenn Hund und Tasche zusammen höchstens ${CABIN.limitKg} kg wiegen; mit einer typischen weichen Tasche bleiben etwa ${num(CABIN_MAX_DOG)} kg für den Hund. ${nCabin} Rassen hier bleiben über ihren ganzen Gewichtsbereich darunter, ${nSome} weitere passen, wenn der einzelne Hund eher leicht ist. Nutze den Filter „Flugzeugtauglich“ in der Rassenliste. US-Airlines setzen oft keine Gewichtsgrenze, aber die Tasche muss unter den Sitz passen.`],
      ["Woher stammen die Größenangaben?", "Größen und Gewichte stammen aus den Rassestandards des American Kennel Club, ergänzt um Standards der FCI, des UKC und der Rasseclubs für Rassen, die der AKC nicht anerkennt. Designer- und Mischlingsrassen haben keinen Standard, ihre Bereiche sind typische Werte. Einzelne Hunde können außerhalb aller angegebenen Bereiche liegen."],
    ];
  }
  function faqBlock() {
    return `<section class="card faq" aria-labelledby="faq-h">
      <h2 id="faq-h">Fragen zur Hundegröße</h2>
${faqs().map(([q, a]) => `      <details><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join("\n")}
    </section>`;
  }
  function ldBlock() {
    const ld = { "@context": "https://schema.org", "@graph": [
      { "@type": "WebApplication", name: D.SITE_NAME_DE, inLanguage: "de", url: `${L.SITE}/de/`, image: `${L.SITE}/img/og-image-de.png`, applicationCategory: "ReferenceApplication", operatingSystem: "Any", browserRequirements: "Requires JavaScript", offers: { "@type": "Offer", price: "0", priceCurrency: "EUR" }, description: desc },
      { "@type": "FAQPage", mainEntity: faqs().map(([q, a]) => ({ "@type": "Question", name: q, acceptedAnswer: { "@type": "Answer", text: a } })) },
    ] };
    return `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, "\\u003c")}</script>`;
  }
};
